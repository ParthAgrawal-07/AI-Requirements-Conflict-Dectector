"""AI resolution suggestions with human feedback (Madhav — US-45, FR-68, FR-94, NFR-36, DR-04,
DR-20; design update §3.7; ADR-24).

**Generation.** Every finding gets one live :class:`~app.models.Suggestion`: requested after the
finding is committed (``analysis.after_run``) or when someone opens it, generated by the
``suggestions.generate`` task with Keval's prompt (``app.classification.suggest``), so findings
and the map never wait for it. Over budget, it waits (``waiting_budget``) and is asked again when
opened; an invalid reply, after one retry, is ``failed``. *Regenerate* with an instruction
supersedes it with a new one. Example re-use is an experiment, off unless the project switches
``use_feedback_examples`` on, and then only with this project's own decisions (SX-23, SX-30).

**Feedback.** Each response is one append-only row (``suggestion_feedback``): the six outcomes —
accepted, accepted after editing, rejected (changes the meaning / infeasible / missed context),
deferred — plus *prefer* (owners mark the option they back before anyone opens a change),
*regenerate*, thumbs and the analysts' 1–5 correctness rating.

**Accepting never changes a requirement** (DR-04). It returns a *pre-fill*: the text and the
links the change editor opens with — a change request on the target requirement (Bansil's intake
takes ``source_suggestion_id``), or, for the member's own Proposed requirement, a new post that
supersedes it. People then review and merge as for any change.
"""

