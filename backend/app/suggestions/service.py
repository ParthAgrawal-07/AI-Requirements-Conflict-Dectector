GENERATE = "suggestions.generate"
EXAMPLES = 5
REJECTIONS = ("rejected_meaning", "rejected_infeasible", "rejected_missing_context")


@dataclass
class Prefill:
    """What the change editor (or the composer) opens with after an acceptance."""

    kind: str  # "change_request" or "post" (supersedes the member's own Proposed requirement)
    requirement_id: uuid.UUID
    proposed_body: str
    source_suggestion_id: uuid.UUID
    finding_id: uuid.UUID
    issue_id: uuid.UUID | None
    issue_number: int | None
    tbd_slots: list[str] = field(default_factory=list)  # to fill before it can be opened


@dataclass
class FeedbackResult:
    feedback: SuggestionFeedback
    prefill: Prefill | None = None
    regenerated: Suggestion | None = None


def live(db: Session, finding_id: uuid.UUID) -> Suggestion | None:
    return db.scalar(
        select(Suggestion).where(
            Suggestion.finding_id == finding_id, Suggestion.status != SUPERSEDED
        )
    )


def request(
    db: Session,
    finding: Finding,
    *,
    requested_by: uuid.UUID | None = None,
    instruction: str | None = None,
    change_request_id: uuid.UUID | None = None,
) -> tuple[Suggestion, bool]:
    """The finding's live suggestion, or a new pending one (and whether it is new; commits).
    With an ``instruction`` the live one is superseded: that is a regeneration."""
    current = live(db, finding.id)
    if current is not None and instruction is None and current.status != FAILED:
        return current, False
    if current is not None:
        current.status = SUPERSEDED
        db.flush()
    row = Suggestion(
        finding_id=finding.id,
        project_id=finding.project_id,
        category=finding.category.value,
        status=PENDING,
        instruction=instruction,
        requested_by=requested_by,
        change_request_id=change_request_id,
    )
    try:
        with db.begin_nested():
            db.add(row)
    except IntegrityError:
        # Another request made the live one first — both owners opening a new conflict issue at
        # once, or the run's own request racing an opened finding: use theirs.
        theirs = live(db, finding.id)
        if theirs is None:  # pragma: no cover - the unique index names only live rows
            raise
        db.commit()
        return theirs, False
    db.commit()
    return row, True


def examples(db: Session, project: Project, category: str) -> list[Example]:
    """This project's latest decisions for the category (the opt-in experiment, SX-30)."""
    if not project.use_feedback_examples:
        return []
    rows = db.execute(
        select(SuggestionFeedback, Suggestion)
        .join(Suggestion, Suggestion.id == SuggestionFeedback.suggestion_id)
        .where(
            Suggestion.project_id == project.id,
            Suggestion.category == category,
            SuggestionFeedback.action.in_((ACCEPTED, ACCEPTED_EDITED, *REJECTIONS)),
        )
        .order_by(SuggestionFeedback.created_at.desc())
        .limit(EXAMPLES)
    ).tuples()
    found: list[Example] = []
    for feedback, suggestion in rows:
        index = feedback.option_index or 0
        text = feedback.final_text or (
            suggestion.options[index]["text"] if index < len(suggestion.options) else ""
        )
        if text:
            found.append(Example(category, feedback.action, text))
    return found


def generate(db: Session, suggestion_id: uuid.UUID, llm: LLMClient) -> Suggestion | None:
    """The ``suggestions.generate`` task body: ask for the options and store them."""
    row = db.scalar(select(Suggestion).where(Suggestion.id == suggestion_id).with_for_update())
    if row is None or row.status not in (PENDING, WAITING_BUDGET):
        db.rollback()
        return row
    finding = db.get(Finding, row.finding_id)
    project = db.get(Project, row.project_id)
    requirements = involved_requirements(db, finding) if finding else []
    if finding is None or project is None or finding.is_stale or not requirements:
        row.status, row.error = FAILED, "finding_gone"
        db.commit()
        return row
    inputs = [as_input(r) for r in requirements]
    pack = ContextPackBuilder(db).build(project, query_text=" ".join(r.body for r in requirements))
    try:
        output, calls = propose(
            row.category,
            inputs,
            finding.explanation or finding.rationale,
            llm=llm,
            pack=pack,
            project_id=project.id,
            instruction=row.instruction,
            examples=examples(db, project, row.category),
        )
    except BudgetExceededError:
        row.status, row.error = WAITING_BUDGET, "budget_exhausted"
        db.commit()
        return row
    row.llm_calls += calls
    if output is None:
        row.status, row.error = FAILED, "no_valid_options"
    else:
        by_label = {i.id: r.id for i, r in zip(inputs, requirements, strict=True)}
        row.options = [
            {
                **option.model_dump(),
                "target_requirement_id": str(by_label[option.target]) if option.target else None,
            }
            for option in output.options
        ]
        row.status, row.error = READY, None
        row.prompt_version, row.model = SUGGEST_VERSION, llm.model
        row.context_version = pack.context_version
        row.ready_at = datetime.now(UTC)
    db.commit()
    bus.publish(
        suggestion_ready(
            workspace_id=project.workspace_id,
            project_id=project.id,
            suggestion_id=row.id,
            finding_id=finding.id,
            status=row.status,
        )
    )
    return row


def preferences(db: Session, suggestion: Suggestion) -> list[tuple[User, int]]:
    """Each member's latest *prefer* on this suggestion: "Riya ✓ Option B · Arjun ✓ Option B"."""
    latest: dict[uuid.UUID, int] = {}
    for feedback in db.scalars(
        select(SuggestionFeedback)
        .where(
            SuggestionFeedback.suggestion_id == suggestion.id, SuggestionFeedback.action == PREFER
        )
        .order_by(SuggestionFeedback.created_at, SuggestionFeedback.id)
    ):
        if feedback.user_id is not None and feedback.option_index is not None:
            latest[feedback.user_id] = feedback.option_index
    users = {u.id: u for u in db.scalars(select(User).where(User.id.in_(latest)))}
    return [(users[u], option) for u, option in latest.items() if u in users]


def my_outcome(db: Session, suggestion: Suggestion, user_id: uuid.UUID) -> str | None:
    return db.scalar(
        select(SuggestionFeedback.action)
        .where(
            SuggestionFeedback.suggestion_id == suggestion.id,
            SuggestionFeedback.user_id == user_id,
            SuggestionFeedback.action.in_(OUTCOMES),
        )
        .order_by(SuggestionFeedback.created_at.desc())
        .limit(1)
    )


def _auto_issue(db: Session, finding: Finding) -> Issue | None:
    from app.services.issues import auto_issue_of

    return auto_issue_of(db, finding)


def _prefill(
    db: Session,
    ctx: AccessContext,
    suggestion: Suggestion,
    finding: Finding,
    text: str,
    option: dict[str, Any],
) -> Prefill:
    target_id = option.get("target_requirement_id")
    if not target_id:
        raise BadRequestError(
            "This option records a link and changes no requirement: record it on the requirement",
            code="no_target",
        )
    requirement = db.get(Requirement, uuid.UUID(target_id))
    if requirement is None:
        raise ConflictError("The requirement this option changes is gone", code="target_gone")
    own_proposal = requirement.state in (
        RequirementState.PROPOSED,
        RequirementState.UNDER_REVIEW,
    ) and (requirement.owner_id == ctx.user.id)
    issue = _auto_issue(db, finding)
    return Prefill(
        kind="post" if own_proposal else "change_request",
        requirement_id=requirement.id,
        proposed_body=text,
        source_suggestion_id=suggestion.id,
        finding_id=finding.id,
        issue_id=issue.id if issue else None,
        issue_number=issue.number if issue else None,
        tbd_slots=list(option.get("tbd_slots") or []) if TBD in text else [],
    )


def record_feedback(
    db: Session,
    ctx: AccessContext,
    suggestion: Suggestion,
    *,
    action: str,
    option_index: int | None = None,
    final_text: str | None = None,
    reason: str | None = None,
    instruction: str | None = None,
    expert_rating: int | None = None,
) -> FeedbackResult:
    """Record one response (append-only; commits). See the module doc for what each one does."""
    if suggestion.status == SUPERSEDED:
        raise ConflictError("A newer suggestion replaced this one", code="superseded")
    if action != REGENERATE and suggestion.status != READY:
        raise ConflictError("The suggestion is not ready yet", code="not_ready")
    if action in CHOICES:
        if option_index is None or not 0 <= option_index < len(suggestion.options):
            raise BadRequestError("Choose one of the options", code="option_required")
    else:
        option_index = None
    final = (final_text or "").strip() or None
    if action == ACCEPTED_EDITED and final is None:
        raise BadRequestError("Send the edited text", code="final_text_required")
    if action == REGENERATE and not (instruction and instruction.strip()):
        raise BadRequestError(
            "Say what the new options should respect", code="instruction_required"
        )
    if action == EXPERT_RATING and not ctx.can("finding.review"):
        raise ForbiddenError("Only reviewers rate suggestions for the correctness study")
    if action in (ACCEPTED, ACCEPTED_EDITED) and not (
        ctx.can("rcr.open") or ctx.can("req.propose")
    ):
        raise ForbiddenError("Accepting opens a change: you need to be able to propose one")
    finding = db.get(Finding, suggestion.finding_id)
    if finding is None:  # pragma: no cover - cascades with the finding
        raise ConflictError("The finding is gone", code="finding_gone")

    prefill = None
    if action in (ACCEPTED, ACCEPTED_EDITED) and option_index is not None:
        option = suggestion.options[option_index]
        prefill = _prefill(db, ctx, suggestion, finding, final or option["text"], option)
    row = SuggestionFeedback(
        suggestion_id=suggestion.id,
        user_id=ctx.user.id,
        action=action,
        option_index=option_index,
        final_text=final if action == ACCEPTED_EDITED else None,
        reason=(reason or "").strip() or None,
        instruction=((instruction or "").strip() or None) if action == REGENERATE else None,
        expert_rating=expert_rating if action == EXPERT_RATING else None,
        # Wall-clock time: several responses in one transaction must still be ordered.
        created_at=func.clock_timestamp(),
    )
    db.add(row)
    db.commit()
    regenerated = None
    if action == REGENERATE:
        regenerated, _ = request(
            db,
            finding,
            requested_by=ctx.user.id,
            instruction=row.instruction,
            change_request_id=suggestion.change_request_id,
        )
    return FeedbackResult(feedback=row, prefill=prefill, regenerated=regenerated)


def stats(db: Session, project: Project) -> dict[str, Any]:
    """The CP2 numbers (NFR-36): outcomes per category, acceptance, expert ratings, latency.

    Each person's latest outcome per suggestion counts once. Acceptance is reported next to the
    expert ratings because accepting is **not** proof a suggestion was right."""
    suggestions = list(db.scalars(select(Suggestion).where(Suggestion.project_id == project.id)))
    by_id = {s.id: s for s in suggestions}
    feedback = list(
        db.scalars(
            select(SuggestionFeedback)
            .where(SuggestionFeedback.suggestion_id.in_(by_id))
            .order_by(SuggestionFeedback.created_at, SuggestionFeedback.id)
        )
    )
    latest: dict[tuple[uuid.UUID, uuid.UUID | None], str] = {}
    ratings: dict[str, list[int]] = defaultdict(list)
    regenerations = 0
    for row in feedback:
        category = by_id[row.suggestion_id].category
        if row.action in OUTCOMES:
            latest[(row.suggestion_id, row.user_id)] = row.action
        elif row.action == EXPERT_RATING and row.expert_rating is not None:
            ratings[category].append(row.expert_rating)
        elif row.action == REGENERATE:
            regenerations += 1
    outcomes: dict[str, Counter[str]] = defaultdict(Counter)
    for (suggestion_id, _), action in latest.items():
        outcomes[by_id[suggestion_id].category][action] += 1
    categories = sorted({s.category for s in suggestions} | set(ratings))
    latencies = sorted(
        (s.ready_at - s.created_at).total_seconds() for s in suggestions if s.ready_at
    )
    total = sum(sum(c.values()) for c in outcomes.values())
    accepted = sum(c[ACCEPTED] + c[ACCEPTED_EDITED] for c in outcomes.values())
    every_rating = [r for values in ratings.values() for r in values]
    return {
        "suggestions": len([s for s in suggestions if s.status != SUPERSEDED]),
        "by_status": dict(Counter(s.status for s in suggestions)),
        "regenerations": regenerations,
        "outcomes_total": total,
        "acceptance_rate": round(accepted / total, 3) if total else None,
        "categories": [
            {
                "category": category,
                "outcomes": {action: outcomes[category][action] for action in OUTCOMES},
                "expert_ratings": len(ratings[category]),
                "expert_mean": round(statistics.mean(ratings[category]), 2)
                if ratings[category]
                else None,
            }
            for category in categories
        ],
        "expert_ratings": len(every_rating),
        "expert_correct_share": round(sum(r >= 4 for r in every_rating) / len(every_rating), 3)
        if every_rating
        else None,
        "latency_p90_seconds": round(latencies[int(0.9 * (len(latencies) - 1))], 1)
        if latencies
        else None,
        "deferred": sum(c[DEFERRED] for c in outcomes.values()),
    }
